function kc = ot_killchain()
%OT_KILLCHAIN Defensive model of a phishing -> ransomware kill chain.
%  Pure reference/threat-modelling data (no functional attack code).
%  Maps each stage to MITRE ATT&CK for ICS and NIST CSF 2.0, with a
%  defensive control and a timing window (hours into the "live" period).
add = @(name,attack,csf,control,h0,h1) struct('name',name,'attack',attack, ...
        'csf',csf,'control',control,'h0',h0,'h1',h1);
kc(1) = add("1. Initial access (spearphishing)", "TA0001 / T0865 Spearphishing Attachment", ...
    "PROTECT / DETECT", "Sakerhetsmedvetenhet, e-postfiltrering, phishing-resistent MFA", 58, 62);
kc(2) = add("2. Credential access", "TA0006 / T0859 Valid Accounts", ...
    "PROTECT (PR.AA)", "MFA, least privilege, kontoovervakning", 64, 68);
kc(3) = add("3. Lateral movement IT -> OT", "T0886 Remote Services", ...
    "PROTECT (PR.IR)", "Segmentering IT/OT, zero-trust, jump-host", 70, 76);
kc(4) = add("4. Manipulate / inhibit control", "T0836 Modify Parameter", ...
    "DETECT (DE.CM)", "Avvikelsedetektion, integritetsskydd for givare", 78, 82);
kc(5) = add("5. Impact (loss of availability)", "T0826 Loss of Availability / T0813 Denial of Control", ...
    "RESPOND / RECOVER", "Immutabel backup, IR-plan, NIS2-rapportering", 80, 86);
end
